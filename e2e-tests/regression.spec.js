import { test, expect } from '@playwright/test'
import { resetDatabase, createUser, apiLogin, createBlogViaApi, login, createBlog } from './test_helper.js'
const credentials = { username: 'writer', name: 'Test Writer', password: 'local-test-password' }
test.beforeEach(async ({ request }) => {
  await resetDatabase(request)
  await createUser(request, credentials)
})
test('login survives reload; creation, liking, user totals and owner deletion stay synchronized', async ({ page, request }) => {
  await page.goto('/')
  await login(page, credentials)
  await page.reload()
  await expect(page.getByRole('button', { name: 'logout', exact: true })).toBeVisible()
  await createBlog(page, { title: 'Refactor regression', author: 'Test Writer', url: 'https://example.com/regression' })
  await page.getByRole('link', { name: 'Refactor regression', exact: true }).click()
  await page.getByRole('button', { name: 'Like', exact: true }).click()
  await expect(page.getByTestId('like-count')).toHaveText('1 like')
  await page.reload()
  await expect(page.getByTestId('like-count')).toHaveText('1 like')
  await page.getByRole('link', { name: 'users', exact: true }).click()
  await expect(page.getByRole('row', { name: /Test Writer/ })).toContainText('1')
  await page.getByRole('link', { name: 'Test Writer', exact: true }).click()
  await page.getByRole('link', { name: 'Refactor regression', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page).toHaveURL('/')
  await expect(page.getByRole('link', { name: 'Refactor regression', exact: true })).toHaveCount(0)
  expect(await (await request.get('http://localhost:3001/api/blogs')).json()).toEqual([])
  await page.getByRole('link', { name: 'users', exact: true }).click()
  await expect(page.getByRole('row', { name: /Test Writer/ })).toContainText('0')
})
test('a guest can add a persistent anonymous comment without owner controls', async ({ page, request }) => {
  const { token } = await apiLogin(request, credentials)
  const blog = await createBlogViaApi(request, token, { title: 'Public discussion', author: 'Writer', url: 'https://example.com/discuss' })
  await page.goto(`/blogs/${blog.id}`)
  await expect(page.getByRole('button', { name: 'Delete', exact: true })).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Comment', exact: true }).fill('A guest contribution')
  await page.getByRole('button', { name: 'add comment' }).click()
  await expect(page.getByText('A guest contribution')).toBeVisible()
  await page.reload()
  await expect(page.getByText('A guest contribution')).toBeVisible()
})
